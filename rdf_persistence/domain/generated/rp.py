class TenantAccess(Policy, Described, AggregateRoot):
    """
    The access record of a tenant: its label, state and database name, with the grants and prohibitions that say who may do what in it.
    """
    state: TenantState = Field(default=..., title="State", description="""Where the tenant is in its life.""")
    database_name: str = Field(default=..., title="Database name", description="""The name of the tenant's database.""")
    grants: Optional[list[Grant]] = Field(default=None, title="Grants", description="""The permissions given in the tenant, by role or as direct actions; they live in the access record's graph.""")
    prohibitions: Optional[list[Prohibition]] = Field(default=None, title="Prohibitions", description="""The actions forbidden in the tenant; they live in the access record's graph.""")
    id: str = Field(default=..., title="Identifier", description="""The IRI that identifies the object.""")
    label: str = Field(default=..., title="Label", description="""The preferred label of the object.""")
    description: Optional[str] = Field(default=None, title="Description", description="""A free-text description of the object.""")

    @field_validator('label')
    def pattern_label(cls, v):
        pattern=re.compile(r"^.{1,200}$")
        if isinstance(v, list):
            for element in v:
                if isinstance(element, str) and not pattern.search(element):
                    err_msg = f"Invalid label format: {element}"
                    raise ValueError(err_msg)
        elif isinstance(v, str) and not pattern.search(v):
            err_msg = f"Invalid label format: {v}"
            raise ValueError(err_msg)
        return v


class StoredFile(ConfiguredBaseModel):
    """
    A mixin for the current content of a kept file; the bytes live in the tenant's bucket under the file key.
    """
    file_name: Optional[str] = Field(default=None, title="File name", description="""The name of the file as uploaded.""")
    media_type: Optional[str] = Field(default=None, title="Media type", description="""The media type of the file.""")
    byte_size: Optional[int] = Field(default=None, title="Byte size", description="""The size of the file in bytes.""")
    sha256: Optional[str] = Field(default=None, title="SHA-256", description="""The SHA-256 digest of the file, in lowercase hexadecimal.""")
    uploaded: Optional[datetime ] = Field(default=None, title="Uploaded", description="""The time the file was uploaded.""")
    uploaded_by: Optional[str] = Field(default=None, title="Uploaded by", description="""The principal that uploaded the file.""")
    file_key: Optional[str] = Field(default=None, title="File key", description="""The random key of the file in the tenant's bucket.""")

    @field_validator('sha256')
    def pattern_sha256(cls, v):
        pattern=re.compile(r"^[0-9a-f]{64}$")
        if isinstance(v, list):
            for element in v:
                if isinstance(element, str) and not pattern.search(element):
                    err_msg = f"Invalid sha256 format: {element}"
                    raise ValueError(err_msg)
        elif isinstance(v, str) and not pattern.search(v):
            err_msg = f"Invalid sha256 format: {v}"
            raise ValueError(err_msg)
        return v


