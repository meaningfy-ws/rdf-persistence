"""The OpenAPI component schemas the service publishes (PD-24).

The generator writes, next to the context, the component schema of every class of a schema
(``generation.components``); this reads those files and keeps the classes the routes mention and the
classes those refer to. Needs no LinkML generator, so a running service can build its document.
"""

import json
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

from rdf_persistence.services.artifacts import COMPONENT_REFERENCES, COMPONENTS_FILE, REF, SCHEMAS
from rdf_persistence.services.schema import PACKAGE_DIR

TOOLKIT_FOLDER = PACKAGE_DIR / "domain" / "generated" / "service"

# One component schema: JSON data of the OpenAPI document, not a model of ours.
JsonSchema = dict[str, Any]


def read_components(folder: Path) -> dict[str, JsonSchema]:
    """The component schemas the generator wrote to ``folder``, by class name.

    Raises:
        OSError: The folder has no components file (it was generated by an older toolkit).
    """
    document = json.loads((folder / COMPONENTS_FILE).read_text(encoding="utf-8"))
    schemas: dict[str, JsonSchema] = document[SCHEMAS]
    return schemas


def _references(node: Any) -> Iterator[str]:
    """The names of the component schemas a JSON Schema node refers to."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key == REF and isinstance(value, str) and value.startswith(COMPONENT_REFERENCES):
                yield value.removeprefix(COMPONENT_REFERENCES).split("/")[0]
            else:
                yield from _references(value)
    elif isinstance(node, list):
        for value in node:
            yield from _references(value)


def component_schemas(folders: Iterable[Path], roots: Iterable[str]) -> dict[str, JsonSchema]:
    """The schemas of the classes ``roots`` and of what they refer to, by name, sorted.

    ``folders`` hold the generated components of the application's schema and of the toolkit's own
    bodies; a class both describe (the metamodel's) is the same definition, and a later folder wins.

    Raises:
        OSError: A folder has no components file.
        KeyError: A root is a class of none of the folders.
    """
    available: dict[str, JsonSchema] = {}
    for folder in folders:
        available.update(read_components(folder))
    seen: dict[str, None] = {}
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name not in seen:
            seen[name] = None
            pending.extend(_references(available[name]))
    return {name: available[name] for name in sorted(seen)}
