"""Write the generated reference partials of the docs (documentation-improvements DEC-6).

`public-api.adoc` lists `rdf_persistence.__all__` and `rdf_persistence.testkit.__all__`, one row per
name with its kind and the first sentence of its docstring; `rp-generate-usage.adoc` is the CLI's
help. Run `make docs-reference` to rewrite them; `--check` exits 1 when they are stale.
"""

import inspect
import re
import sys
import types
from pathlib import Path

import rdf_persistence
import rdf_persistence.testkit
from rdf_persistence_generation.cli import build_parser

PARTIALS = Path(__file__).resolve().parents[1] / "modules/ROOT/partials/reference"
HEADER = "// Generated by docs/tools/reference.py (make docs-reference); do not edit.\n"
CHECK = "--check"
CONSTANT = "constant"


def kind(value: object) -> str:
    if inspect.isclass(value):
        return "class"
    if callable(value):
        return "function"
    return CONSTANT


def first_sentence(value: object) -> str:
    if kind(value) == CONSTANT:
        return ""
    doc = inspect.getdoc(value) or ""
    paragraph = " ".join(doc.split("\n\n")[0].split())
    sentence = re.split(r"(?<=\.)\s", paragraph, maxsplit=1)[0]
    return sentence.replace("|", "\\|")


def api_table(module: types.ModuleType) -> str:
    rows = [
        f"|`{name}` |{kind(getattr(module, name))} |{first_sentence(getattr(module, name))}".rstrip()
        for name in sorted(module.__all__, key=str.lower)
    ]
    return (
        '[cols="2,1,6",options="header"]\n|===\n|Name |Kind |What it is\n\n'
        + "\n".join(rows)
        + "\n|===\n"
    )


def cli_usage() -> str:
    """The options of `rp-generate` as a table, built from its parser's actions.

    Not argparse's own help text: its layout changes between Python versions, and the check must
    give the same answer on every supported Python.
    """
    rows = [
        "|`"
        + ", ".join(action.option_strings)
        + (f" {action.metavar or action.dest.upper()}" if action.nargs != 0 else "")
        + f"` |{(action.help or '').replace('|', chr(92) + '|')}"
        for action in build_parser()._actions  # the parser offers no public list of its actions
        if action.option_strings
    ]
    return (
        '[cols="2,5",options="header"]\n|===\n|Option |What it does\n\n'
        + "\n".join(rows)
        + "\n|===\n"
    )


def render() -> dict[str, str]:
    api = (
        HEADER
        + "\n=== `rdf_persistence`\n\n"
        + api_table(rdf_persistence)
        + "\n=== `rdf_persistence.testkit`\n\n"
        + api_table(rdf_persistence.testkit)
    )
    usage = HEADER + "\n" + cli_usage()
    return {"public-api.adoc": api, "rp-generate-usage.adoc": usage}


def main(argv: list[str]) -> int:
    stale = [
        name
        for name, text in render().items()
        if not (PARTIALS / name).is_file() or (PARTIALS / name).read_text() != text
    ]
    if CHECK in argv:
        for name in stale:
            print(f"FAIL the reference partial {name} is stale: run make docs-reference")
        return 1 if stale else 0
    PARTIALS.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (PARTIALS / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
